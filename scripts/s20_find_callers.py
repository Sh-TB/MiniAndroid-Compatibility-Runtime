#!/usr/bin/env python3
"""S20: find all call sites of a given method (class+name) in the DEX."""
import struct, sys, zipfile

apk, cls, meth = sys.argv[1], sys.argv[2], sys.argv[3]
d = zipfile.ZipFile(apk).read('classes.dex')
u4 = lambda o: struct.unpack_from('<I', d, o)[0]
u2 = lambda o: struct.unpack_from('<H', d, o)[0]

def uleb(p):
    r = s = 0
    while True:
        b = d[p + s]; r |= (b & 0x7f) << (7 * s); s += 1
        if not (b & 0x80): return r, p + s

s_sz, s_off = u4(0x38), u4(0x3c)
t_sz, t_off = u4(0x40), u4(0x44)
p_sz, p_off = u4(0x48), u4(0x4c)
m_sz, m_off = u4(0x58), u4(0x5c)
c_sz, c_off = u4(0x60), u4(0x64)
strs = []
for i in range(s_sz):
    off = u4(s_off + 4 * i); n, p = uleb(off)
    strs.append(d[p:p + n].decode('utf-8', 'replace'))
td = lambda i: strs[u4(t_off + 4 * i)]

def proto_sig(i):
    base = p_off + 12 * i
    po = u4(base + 8)
    if po == 0: return []
    n = u4(po)
    return [td(u2(po + 4 + 2 * k)) for k in range(n)]

def method_ref(i):
    o = m_off + 8 * i
    return td(u2(o)), strs[u4(o + 4)], proto_sig(u2(o + 2))

# find method_idx of target
target_mi = None
for i in range(m_sz):
    c, n, pr = method_ref(i)
    if c == cls and n == meth:
        target_mi = i
        print(f'target method_idx={i} {c}.{n}({",".join(pr)})')
        break
if target_mi is None:
    sys.exit('not found')

# scan all classes' code for invoke-* referencing target_mi
SZ = {o: 1 for o in range(0x100)}
for o in (0x12,0x13,0x15,0x16,0x1a,0x1c,0x1d,0x1e,0x1f,0x20,0x21,0x22,0x23,0x24,
          0x25,0x26,0x60,0x61,0x62,0x63,0x64,0x65,0x66,0x67,0x68,0x69,0x6a,0x6b,
          0x6c,0x6d,0xd0,0xd1,0xd2,0xd3,0xd4,0xd5,0xd6,0xd7,0xd8,0xd9,0xda,0xdb,
          0xdc,0xdd,0xde,0xdf,0xe0,0xe1,0xe2,0xe3,0xe4,0xe5,0xe6,0xe7,0xe8,0xe9,
          0xea,0xeb,0xec,0xed,0xee,0xef,0xf2,0xf3,0xf4,0xf5,0xf6,0xf7,0xf8,0xf9,
          0xfb,0xfc,0xfd,0xfe,0xff,0x02,0x05,0x08,0x14,0x17,0x29,0x33,0x34,0x35,
          0x36,0x37,0x38,0x39,0x3a,0x3b,0x3c,0x3d,0x44,0x45,0x46,0x47,0x48,0x49,
          0x4a,0x4b,0x4c,0x4d,0x4e,0x4f,0x50,0x51,0x52,0x53,0x54,0x55,0x56,0x57,
          0x58,0x59,0x5a,0x5b,0x5c,0x5d,0x5e,0x5f,0x90,0x91,0x92,0x93,0x94,0x95,
          0x96,0x97,0x98,0x99,0x9a,0x9b,0x9c,0x9d,0x9e,0x9f,0xa0,0xa1,0xa2,0xa3,
          0xa4,0xa5,0xa6,0xa7,0xa8,0xa9,0xaa,0xab,0xac,0xad,0xae,0xaf,0xb0,0xb1,
          0xb2,0xb3,0xb4,0xb5,0xb6,0xb7,0xb8,0xb9,0xba,0xbb,0xbc,0xbd,0xbe,0xbf,
          0xc0,0xc1,0xc2,0xc3,0xc4,0xc5,0xc6,0xc7,0xc8,0xc9,0xca,0xcb,0xcc,0xcd,
          0xce,0xcf,0x79,0x7a,0x7b,0x7c,0x7d,0x7e,0x7f,0x80,0x81,0x82,0x83,0x84,
          0x85,0x86,0x87,0x88,0x89,0x8a,0x8b,0x8c,0x8d,0x8e,0x8f):
    SZ[o] = 2
for o in (0x6e,0x6f,0x70,0x71,0x72,0x74,0x75,0x76,0x77,0x78):
    SZ[o] = 3
for o in (0x18,0x19,0x1b,0x2a,0x2b,0x2c):
    SZ[o] = 3

for i in range(c_sz):
    o = c_off + 32 * i
    desc = td(u4(o))
    cdo = u4(o + 24)
    if cdo == 0: continue
    try:
        n_sf, p = uleb(cdo); n_if_, p = uleb(p); n_dm, p = uleb(p); n_vm, p = uleb(p)
        prev = 0
        for _ in range(n_sf):
            _, p = uleb(p); _, p = uleb(p)
        for _ in range(n_if_):
            _, p = uleb(p); _, p = uleb(p)
        for kind, cnt in (('direct', n_dm), ('virtual', n_vm)):
            prev_m = 0
            for _ in range(cnt):
                diff, p = uleb(p); af, p = uleb(p); co, p = uleb(p)
                prev_m += diff
                mo = m_off + 8 * prev_m
                mname = strs[u4(mo + 4)]
                if co == 0: continue
                isz = u4(co + 12)
                base = co + 16
                pc = 0
                while pc < isz:
                    w = u2(base + 2 * pc)
                    op = w & 0xff
                    if op in (0x6e, 0x6f, 0x70, 0x71, 0x72):
                        mi = u2(base + 2 * (pc + 1))
                        if mi == target_mi:
                            w1 = u2(base + 2 * (pc + 2))
                            A = (w >> 12) & 0xf; G = (w >> 8) & 0xf
                            C = w1 & 0xf; D_ = (w1 >> 4) & 0xf; E = (w1 >> 8) & 0xf; F_ = (w1 >> 12) & 0xf
                            regs = [C, D_, E, F_, G][:A] if A <= 5 else []
                            print(f'CALLER {desc}.{mname} [{kind}] pc={pc:#x} op={op:#04x} regs={regs}')
                        pc += 3; continue
                    if op in (0x74, 0x75, 0x76, 0x77, 0x78):
                        mi = u2(base + 2 * (pc + 1))
                        if mi == target_mi:
                            first = u2(base + 2 * (pc + 2))
                            size = (w >> 8) & 0xff
                            print(f'CALLER {desc}.{mname} [{kind}] pc={pc:#x} op={op:#04x} RANGE first=v{first} size={size}')
                        pc += 3; continue
                    pc += SZ.get(op, 1)
    except Exception:
        continue
