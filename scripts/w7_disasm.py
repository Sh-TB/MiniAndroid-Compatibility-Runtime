def main():
    apk, cls, meth = sys.argv[1], sys.argv[2], sys.argv[3]
    if not cls.endswith(';'): cls += ';'
    z = zipfile.ZipFile(apk)
    data = z.read('classes.dex')
    dx = Dex(data)
    off = dx.find_class(cls)
    info = dx.class_methods(off)
    code = None
    for kind in ('direct', 'virtual'):
        for (m, d, a, sz, co) in info[kind]:
            if m == meth and co:
                code = co
    if code is None:
        print('method not found'); return
    insns_size = dx.u(code + 12, 4)
    insns_off = code + 16
    pc = 0
    while pc < insns_size:
        o = insns_off + pc * 2
        w = dx.u(o, 2)
        op = w & 0xff
        name = OPNAMES.get(op, f'op{op:#04x}')
        extra = ''
        if op in (0x1a,):  # const-string
            idx = dx.u(o + 2, 2)
            extra = ' "' + dx.string(idx)[:40] + '"'
        elif op in (0x22, 0x1c, 0x1f, 0x20, 0x23, 0x24, 0x25):
            idx = dx.u(o + 2, 2)
            extra = ' ' + dx.type_str(idx) if op != 0x24 and op != 0x25 else ' ' + dx.method_ref(idx)[0]
        elif op in (0x6e, 0x6f, 0x70, 0x71, 0x72, 0x74, 0x75, 0x76, 0x77, 0x78):
            idx = dx.u(o + 2, 2)
            c, n, p = dx.method_ref(idx)
            extra = f' {c}.{n}{p}'
        elif op in (0x52, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58,
                    0x59, 0x5a, 0x5b, 0x5c, 0x5d, 0x5e, 0x5f,
                    0x60, 0x61, 0x62, 0x63, 0x64, 0x65, 0x66,
                    0x67, 0x68, 0x69, 0x6a, 0x6b, 0x6c, 0x6d):
            idx = dx.u(o + 2, 2)
            c, n, t = dx.field_ref(idx)
            extra = f' {c}.{n}:{t}'
        elif op in (0x28, 0x29, 0x2a):
            if op == 0x28:
                off8 = (w >> 8) & 0xff
                if off8 > 127: off8 -= 256
                extra = f' -> {pc + off8:#x}'
            elif op == 0x29:
                o16 = dx.u(o + 2, 2)
                if o16 > 32767: o16 -= 65536
                extra = f' -> {pc + o16:#x}'
        elif op in (0x32,0x33,0x34,0x35,0x36,0x37,0x38,0x39,0x3a,0x3b,0x3c,0x3d):
            o16 = dx.u(o + 2, 2)
            if o16 > 32767: o16 -= 65536
            extra = f' -> {pc + o16:#x}'
        elif op == 0x2b or op == 0x2c:
            idx = dx.u(o + 2, 2)
            extra = f' payload@{pc + idx:#x}'
        sz = opsize(op)
        # literal operands for const/lit forms
        try:
            if op in (0x12,):  # const/4
                v = (w >> 8) & 0xf
                if v > 7: v -= 16
                extra += f' #{v}'
            elif op in (0x13, 0x16):  # const/16, const-wide/16
                v = dx.u(o + 2, 2)
                if v > 32767: v -= 65536
                extra += f' #{v}'
            elif op == 0x14:  # const
                extra += f' #{dx.u(o + 2, 4):#x} ({dx.u(o + 2, 4)})'
            elif op == 0x15:  # const/high16
                extra += f' #{dx.u(o + 2, 2) << 16:#x}'
            elif op == 0x17:  # const-wide/32
                v = dx.u(o + 2, 4)
                if v > 2147483647: v -= 4294967296
                extra += f' #{v}'
            elif op == 0x18:  # const-wide
                lo = dx.u(o + 2, 4); hi = dx.u(o + 6, 4)
                q = (hi << 32) | lo
                if q > (1 << 63) - 1: q -= (1 << 64)
                extra += f' #{q:#x} ({q})'
            elif op == 0x19:  # const-wide/high16
                extra += f' #{dx.u(o + 2, 2) << 48:#x}'
            elif op in (0xd8, 0xd9, 0xda, 0xdb, 0xdc, 0xdd, 0xde, 0xdf,
                        0xe0, 0xe1, 0xe2):  # binop/lit8 (22b: lit in 2nd word hi)
                v = (dx.u(o + 2, 2) >> 8) & 0xff
                if v > 127: v -= 256
                extra += f' #{v}'
            elif op in (0xd0, 0xd1, 0xd2, 0xd3, 0xd4, 0xd5, 0xd6, 0xd7):
                v = dx.u(o + 2, 2)
                if v > 32767: v -= 65536
                extra += f' #{v}'
        except Exception as e:
            extra += f' <literr>'
        print(f'{pc:#06x}: {name}{extra}')
        pc += sz


if __name__ == '__main__':
    main()
