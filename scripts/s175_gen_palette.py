#!/usr/bin/env python3
"""S175: generate miniandroid/src/resources/material_you_palette.h — the 165-entry
{framework resid -> ARGB} baseline Material You palette (Coder-3 A17, #527).

Sources (authoritative, both fetched fresh today):
  1. android-34 R$color constants — platform-34-ext7_r03 android.jar from
     dl.google.com (the purged vanilla platform-34 jar, sha16 923bafccf73aef99
     per the S153 purge record, is gone from the repository; the ext7 build's
     system_* ID assignment is validated EXACT against the three IDs the
     coder pinned from the app's own queries: system_primary_light
     0x01060060, system_on_primary_light 0x01060061,
     system_primary_container_light 0x0106005e).
  2. AOSP android-14.0.0_r1 core/res/res/values/colors.xml
     (android.googlesource.com, tag android-14.0.0_r1) — 166 system_* entries.
Join: R$color system_* names ∩ colors.xml system_* names (expected 165/165).
Cross-checks baked in: system_accent1_100 == #C1E8FF (independent
hushenghao/AndroidEasterEggs dump per #527), system_primary_container_light
== #D8E2FF, system_primary_light == #445E91.
"""
import re, sys, zipfile, struct
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from s175_rcolor_parse import parse_rcolor

JAR = "/tmp/platform-34-ext7_r03.jar"
AOSP = Path("/tmp/aosp14_colors.xml")
OUT = Path(__file__).parent.parent / "miniandroid/src/resources/material_you_palette.h"

# --- 1. R$color constants (android-34) ---
with zipfile.ZipFile(JAR) as z:
    data = z.read("android/R$color.class")
rc = parse_rcolor(data)
print(f"R$color int fields: {len(rc)}")

# Validate the three pinned IDs
for name, want in (("system_primary_light", 0x01060060),
                   ("system_on_primary_light", 0x01060061),
                   ("system_primary_container_light", 0x0106005e)):
    got = rc.get(name)
    assert got == want, f"ID-assignment validation FAILED: {name} 0x{got:08x} != 0x{want:08x}"
print("ID-assignment validation: 3/3 pinned IDs EXACT")

# --- 2. AOSP colors.xml values ---
xml = AOSP.read_text()
vals = {}
for m in re.finditer(r'<color name="([^"]+)">([^<]+)</color>', xml):
    name, v = m.group(1), m.group(2).strip()
    if not name.startswith("system_"):
        continue
    if v.startswith("#"):
        h = v[1:]
        if len(h) == 6:
            argb = 0xFF000000 | int(h, 16)
        elif len(h) == 8:
            argb = int(h, 16)
        else:
            raise ValueError(f"bad color {name}={v}")
        vals[name] = argb
print(f"AOSP system_* colors: {len(vals)}")

# --- 3. Join ---
join = {}
for name, rid in rc.items():
    if name.startswith("system_") and name in vals:
        join[rid] = vals[name]
print(f"JOIN entries: {len(join)}")

# Cross-checks
def argb_of(name):
    for rid, a in join.items():
        pass
    return None
by_name = {n: (r, vals[n]) for n, r in rc.items() if n in vals}
assert by_name["system_accent1_100"][1] == 0xFFC1E8FF, "accent1_100 != C1E8FF"
assert by_name["system_primary_container_light"][1] == 0xFFD8E2FF, "primary_container_light != D8E2FF"
assert by_name["system_primary_light"][1] == 0xFF445E91, "primary_light != 445E91"
print("value cross-checks: 3/3 (C1E8FF / D8E2FF / 445E91)")

rows = sorted(join.items())

# --- 4. Emit header ---
hdr = f"""// material_you_palette.h — Coder-3 A17 baseline Material You palette
// (issue #527), generated by scripts/s175_gen_palette.py — DO NOT EDIT BY HAND.
//
// The dynamic-color baseline: android:color/system_* framework IDs (package
// 0x01) -> their AOSP baseline-palette ARGB values. With no framework_res
// table in-tree (S153 purge), every system_* lookup nullopted and Compose
// materialized Unspecified -> the all-black UI (face 11a38a5a, #527 step 7).
// This table answers them exactly like the framework table would on a real
// API-34 device: the app's dynamicLightColorScheme resolves its COMPLETE
// Material You theme.
//
// Provenance (both authoritative, joined 1:1 by name):
//   IDs   : android-34 R$color via platform-34-ext7_r03 android.jar
//           (dl.google.com; jar sha16 6cea1df3efb77103 — the purged vanilla
//           platform-34 jar, sha16 923bafccf73aef99 per the S153 purge
//           record, is no longer published; the ext7 system_* ID assignment
//           validated EXACT against #527's three app-side pinned IDs:
//           system_primary_light 0x01060060, system_on_primary_light
//           0x01060061, system_primary_container_light 0x0106005e).
//   Values: AOSP android-14.0.0_r1 core/res/res/values/colors.xml
//           (android.googlesource.com tag android-14.0.0_r1; {len(vals)} system_*
//           entries; cross-validated system_accent1_100 == #C1E8FF against
//           the independent hushenghao/AndroidEasterEggs dump, per #527).
// Join: {len(join)} entries (R$color system_* ∩ colors.xml system_*).
// Default path is BYTE-INERT: the lookup misses (nullopt) on every resid
// outside the table, exactly like the code path it falls back from.
#pragma once
#include <cstdint>
#include <cstddef>
#include <optional>

namespace miniandroid::resources {{

struct MaterialYouEntry {{
    uint32_t resid;
    uint32_t argb;
}};

// {len(join)} entries, sorted by resid (binary-search ready).
inline constexpr MaterialYouEntry kMaterialYouPalette[] = {{"""
for rid, a in rows:
    hdr += f"\n    {{0x{rid:08x}u, 0x{a:08x}u}},"
hdr += f"""
}};

// Bounded [S156-MYCULAR] census cap (issue #527: 40 rows).
inline constexpr size_t kMaterialYouCensusCap = 40;

// The ONE palette law: exact-resid lookup, nullopt on miss (byte-inert).
inline std::optional<uint32_t> material_you_palette_lookup(uint32_t resid) {{
    size_t lo = 0, hi = sizeof(kMaterialYouPalette) / sizeof(kMaterialYouPalette[0]);
    while (lo < hi) {{
        size_t mid = (lo + hi) / 2;
        if (kMaterialYouPalette[mid].resid == resid) return kMaterialYouPalette[mid].argb;
        if (kMaterialYouPalette[mid].resid < resid) lo = mid + 1; else hi = mid;
    }}
    return std::nullopt;
}}

}}  // namespace miniandroid::resources
"""
OUT.write_text(hdr)
print(f"wrote {OUT} ({len(hdr)} bytes, {len(rows)} entries)")
