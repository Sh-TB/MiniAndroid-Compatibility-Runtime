#!/usr/bin/env python3
"""P0 SPLIT — extract DalvikExecutionEngine::bridge_to_api from the
dalvik_bridge.cpp mega-TU into five domain dispatch TUs + a thin coordinator.

Laws (P0 mandatory tasks 2-5):
  * verbatim-range extraction: dispatched bytes move unchanged; cuts land
    ONLY at inter-block gap starts and each domain ends exactly at the
    previous block's close — an if-condition never separates from its
    body; original scan order preserved (domain handlers fall through
    with `return false`; the coordinator chains them sequentially).
  * the only body-depth state shared across ranges is the normalized
    `args` binding + the function parameters (census: 383 consumer
    blocks) — carried by DalvikBridgeFrame (references only).
  * file-local helpers: stateless str_* → header-inline; diag_env and
    f356_mp_engine_for keep ONE definition each (coordinator) with
    declarations in the frame header — no per-TU state duplication.
  * DALVIK_SPLIT=0 keeps building the untouched monolith.
"""
import re

SRC = 'src/dex/dalvik_bridge.cpp'
DOMAINS = [('jdk', 8100), ('android_core', 16629), ('ui_graphics', 31137),
           ('app_runtime', 45289)]
NAMES = ['jdk', 'android_core', 'ui_graphics', 'app_runtime', 'io_lang']
COORD_END = 300          # coordinator verbatim body: 203..300
D1_START = 301           # gap start right after block 286-300
LAST_END = 55440         # last block close (void-tail stays coordinator)


def main():
    lines = open(SRC, encoding='utf-8').read().splitlines(keepends=True)
    import json
    c = json.load(open('scripts/p0_census.json'))
    blocks = [(d['a'], d['b']) for d in c['blocks']]
    assert (286, 300) in blocks and (17129, 31136) in blocks, 'anchors moved'
    func_end = c['func_end']
    assert func_end == 55443 and len(lines) == 55995, (func_end, len(lines))

    gaps = []
    prev = 203
    for a, b in blocks:
        if a > prev:
            gaps.append((prev, a - 1))
        prev = b + 1
    if func_end - 1 >= prev:
        gaps.append((prev, func_end - 1))
    starts = [D1_START] + [min(gaps, key=lambda g: abs(g[0] - t))[0]
                           for _, t in DOMAINS]
    ends = [starts[i + 1] - 1 for i in range(4)] + [LAST_END]
    for s, e in zip(starts, ends):
        assert s < e, (s, e)
        for a, b in blocks:
            assert not (a < s <= b), f'cut {s} inside block {a}-{b}'
    print('domain ranges (verbatim):')
    for nm, s, e in zip(NAMES, starts, ends):
        print(f'  bridge_domain_{nm}: [{s}, {e}]  {e - s + 1} lines')

    # ── frame header ─────────────────────────────────────────────────
    fh = []
    fh.append('// ────────────────────────────────────────────────────────────────\n'
              '// dalvik_bridge_frame.h — P0 SPLIT stable dispatch contract.\n'
              '// Carries the ONLY body-depth state shared across the extracted\n'
              '// bridge domain ranges (census: scripts/p0_census.json):\n'
              '// the normalized `args` binding + the bridge_to_api parameters.\n'
              '// All frame members are references — zero copies, zero duplicated\n'
              '// state; the coordinator binds them once per dispatch.\n'
              '// Generated by scripts/p0_split.py; new generic laws go into the\n'
              '// domain TUs (or a new modular law TU), never into the legacy file.\n'
              '// ────────────────────────────────────────────────────────────────\n'
              '#pragma once\n\n')
    fh.append(''.join(lines[0:63]))            # include block (1-63)
    fh.append('#include "dex/dalvik_engine_internal.h"\n\n')
    helpers = ''.join(lines[64:126])           # str_* helpers (65-126)
    helpers = helpers.replace('int32_t str_utf16_unit_count',
                              'inline int32_t str_utf16_unit_count')
    helpers = helpers.replace('bool str_char_at_unit',
                              'inline bool str_char_at_unit')
    fh.append('// Stateless string helpers of the legacy mega-TU, now shared.\n')
    fh.append(helpers)
    fh.append('\n// File-local helpers with STATE: one definition each (in the\n'
              '// coordinator) so the thread_local cache / MediaPlayer map stay\n'
              '// process singletons exactly as before the split.\n'
              'bool diag_env(const char* name);\n')
    fh.append('\nnamespace miniandroid {\n'
              'audio::MediaPlayer* f356_mp_engine_for(uint32_t oid);\n')
    fh.append('namespace dalvik {\n\n'
              'struct DalvikBridgeFrame {\n'
              '    const std::string& class_name;\n'
              '    const std::string& method;\n'
              '    const std::vector<DalvikValue>& args_raw;\n'
              '    const std::vector<DalvikValue>& args;\n'
              '    DalvikValue& result;\n'
              '    ApiCallTrace::Status& status;\n'
              '    uint32_t method_idx_hint;\n'
              '};\n\n')
    fh.append('}  // namespace dalvik\n'
              '}  // namespace miniandroid\n')
    open('src/dex/dalvik_bridge_frame.h', 'w', encoding='utf-8').writelines(fh)

    # ── domain TUs ───────────────────────────────────────────────────
    alias = ('    const std::string& class_name = fr.class_name;\n'
             '    const std::string& method = fr.method;\n'
             '    const std::vector<DalvikValue>& args_raw = fr.args_raw;\n'
             '    const std::vector<DalvikValue>& args = fr.args;\n'
             '    DalvikValue& result = fr.result;\n'
             '    ApiCallTrace::Status& status = fr.status;\n'
             '    uint32_t method_idx_hint = fr.method_idx_hint;\n')
    for nm, s, e in zip(NAMES, starts, ends):
        doc = (f'// ────────────────────────────────────────────────────────────\n'
               f'// dalvik_bridge_domain_{nm}.cpp — P0 SPLIT domain dispatch TU.\n'
               f'// Verbatim range [{s}, {e}] of the bridge_to_api mega-body\n'
               f'// (generated by scripts/p0_split.py from dalvik_bridge.cpp at\n'
               f'// the split commit). Dispatch order = the original scan order:\n'
               f'// unhandled calls fall through via `return false`; the\n'
               f'// coordinator chains the domains sequentially. NEW generic\n'
               f'// laws belong here (or in a new modular law TU) — never back\n'
               f'// in the legacy coordinator.\n'
               f'// ────────────────────────────────────────────────────────────\n'
               f'#include "dex/dalvik_bridge_frame.h"\n\n'
               f'namespace miniandroid {{\n'
               f'namespace dalvik {{\n\n'
               f'bool DalvikExecutionEngine::bridge_domain_{nm}(\n'
               f'    DalvikBridgeFrame& fr) {{\n'
               + alias +
               f'{"".join(lines[s - 1:e])}'
               f'    return false;\n'
               f'}}\n\n'
               f'}}  // namespace dalvik\n'
               f'}}  // namespace miniandroid\n')
        open(f'src/dex/dalvik_bridge_domain_{nm}.cpp', 'w',
             encoding='utf-8').write(doc)

    # ── thin coordinator ─────────────────────────────────────────────
    sig = ''.join(lines[196:202])              # 197..202
    pre = ''.join(lines[202:COORD_END])        # 203..300
    tail = ''.join(lines[55440:55442])         # 55441..55442
    arms = ''.join(lines[55446:55995])         # 55447..55995
    diag = ''.join(lines[127:182])             # 128..182 banner + diag_env
    diag = diag.replace('static bool diag_env', 'bool diag_env', 1)
    f356_body = ''.join(lines[187:192])        # 188..192 verbatim lambda body
    cb = []
    cb.append('// ────────────────────────────────────────────────────────────────\n'
              '// dalvik_bridge.cpp — P0 SPLIT thin dispatch coordinator.\n'
              '// The 55K-line bridge_to_api mega-body moved verbatim into five\n'
              '// domain TUs (dalvik_bridge_domain_*.cpp, generated by\n'
              '// scripts/p0_split.py); this file keeps only: the dispatch\n'
              '// preamble (args normalization, census guard, phase clock), the\n'
              '// sequential domain chain, the void fall-through tail, the\n'
              '// bridge_arm_* arms, and the one-definition shared helpers.\n'
              '// Dispatch precedence is unchanged. NEW generic laws: add to\n'
              '// the domain TUs, NOT here.\n'
              '// ────────────────────────────────────────────────────────────────\n'
              '#include "dex/dalvik_bridge_frame.h"\n\n')
    cb.append(diag)
    cb.append('\nnamespace miniandroid {\n\n'
              'audio::MediaPlayer* f356_mp_engine_for(uint32_t oid) {\n')
    cb.append(f356_body)
    cb.append('}\n\n')
    cb.append('namespace dalvik {\n\n')
    cb.append(sig)
    cb.append(pre)
    cb.append('    DalvikBridgeFrame fr{class_name, method, args_raw, args,\n'
              '                             result, status, method_idx_hint};\n')
    for nm in NAMES:
        cb.append(f'    if (bridge_domain_{nm}(fr)) return true;\n')
    cb.append(tail)
    cb.append('}\n\n'
              '}  // namespace dalvik\n'
              '}  // namespace miniandroid\n\n')
    cb.append(arms)
    open(SRC, 'w', encoding='utf-8').writelines(cb)

    # ── dalvik_engine.h: fwd-decl + 5 member declarations ────────────
    eh_lines = open('src/dex/dalvik_engine.h', encoding='utf-8').read() \
        .splitlines(keepends=True)
    ci = next(i for i, ln in enumerate(eh_lines)
              if ln.startswith('class DalvikExecutionEngine'))
    fwd = ('// P0 SPLIT: dispatch frame for the bridge domain ranges — defined\n'
           '// in dex/dalvik_bridge_frame.h (references only here; no include\n'
           '// to keep the engine-header dependency graph unchanged).\n'
           'namespace miniandroid {\nnamespace dalvik {\n'
           'struct DalvikBridgeFrame;\n}\n}\n\n')
    eh_lines.insert(ci, fwd)
    ai = next(i for i, ln in enumerate(eh_lines)
              if 'bool bridge_arm_5892(' in ln)
    while not eh_lines[ai].rstrip().endswith(';'):
        ai += 1
    eh_lines.insert(ai + 1,
                    '\n    // P0 SPLIT (bridge mega-TU): five domain dispatch ranges of\n'
                    '    // bridge_to_api — verbatim-range extraction, chained in original\n'
                    '    // scan order by the coordinator; frame contract in\n'
                    '    // dex/dalvik_bridge_frame.h.\n'
                    + ''.join(f'  bool bridge_domain_{nm}(DalvikBridgeFrame& fr);\n'
                              for nm in NAMES))
    open('src/dex/dalvik_engine.h', 'w', encoding='utf-8') \
        .writelines(eh_lines)

    # ── manifest / Makefile / CMake parity ───────────────────────────
    mf = open('core_sources.manifest', encoding='utf-8').read()
    mf = mf.replace('src/dex/dalvik_bridge.cpp\n',
                    'src/dex/dalvik_bridge.cpp\n'
                    + ''.join(f'src/dex/dalvik_bridge_domain_{nm}.cpp\n'
                              for nm in NAMES), 1)
    open('core_sources.manifest', 'w', encoding='utf-8').write(mf)

    mk = open('Makefile', encoding='utf-8').read()
    mk_anchor = ('\tdex/dalvik_opcodes_invoke.cpp dex/dalvik_bridge.cpp '
                 'dex/dalvik_engine_tail.cpp\n')
    assert mk_anchor in mk, 'Makefile parts anchor'
    mk = mk.replace(mk_anchor,
                    '\tdex/dalvik_opcodes_invoke.cpp dex/dalvik_engine_tail.cpp\n'
                    + ''.join(f'\tdex/dalvik_bridge_domain_{nm}.cpp \\\n'
                              for nm in NAMES[:-1])
                    + f'\tdex/dalvik_bridge_domain_{NAMES[-1]}.cpp\n', 1)
    open('Makefile', 'w', encoding='utf-8').write(mk)

    cm = open('CMakeLists.txt', encoding='utf-8').read()
    cm_anchor = '    ${CMAKE_CURRENT_SOURCE_DIR}/src/dex/dalvik_bridge.cpp\n'
    assert cm_anchor in cm, 'CMake parts anchor'
    cm = cm.replace(cm_anchor,
                    cm_anchor + ''.join(
                        f'    ${{CMAKE_CURRENT_SOURCE_DIR}}'
                        f'/src/dex/dalvik_bridge_domain_{nm}.cpp\n'
                        for nm in NAMES), 1)
    open('CMakeLists.txt', 'w', encoding='utf-8').write(cm)
    print('frame header + 5 domain TUs + coordinator + build patches written')


if __name__ == '__main__':
    main()
