def compare_resource_type(resource_type: ResourceType) -> Dict[str, Any]:
    """Compare MiniAndroid implementation vs Android reference for a resource type"""
    
    android_ref = ANDROID_REFERENCE_BEHAVIOR[resource_type]
    miniandroid_impl = MINIANDROID_RESOURCE_STATUS[resource_type]
    
    # Determine comparison result
    if not miniandroid_impl["implemented"]:
        result = ComparisonResult.NOT_IMPLEMENTED
    elif len(miniandroid_impl["limitations"]) == 0:
        result = ComparisonResult.MATCH
    elif len(miniandroid_impl["capabilities"]) > len(miniandroid_impl["limitations"]):
        result = ComparisonResult.PARTIAL_MATCH
    else:
        result = ComparisonResult.MISMATCH
    
    return {
        "resource_type": resource_type.value,
        "comparison_result": result.value,
        
        "android_reference": android_ref,
        
        "miniandroid_implementation": miniandroid_impl,
        
        "gap_analysis": {
            "missing_features": miniandroid_impl["limitations"],
            "working_features": miniandroid_impl["capabilities"],
            "critical_gaps": [lim for lim in miniandroid_impl["limitations"] 
                           if any(word in lim.lower() 
                                 for word in ["not", "no", "manual", "stub", "fallback"])],
            "compatibility_score": calculate_compatibility_score(
                len(miniandroid_impl["capabilities"]),
                len(miniandroid_impl["limitations"])
            )
        },
        
        "test_cases": generate_test_cases(resource_type)
    }


def calculate_compatibility_score(capabilities: int, limitations: int) -> int:
    """Calculate compatibility percentage"""
    total = capabilities + limitations
    if total == 0:
        return 0
    return round(capabilities / total * 100)


