// CAMPAIGN 010 R9 — PortableGL-backed GLES surface for MiniAndroid.
//
// PortableGL (rswinkle/PortableGL @ 7cf39dc, MIT) is adopted INSTEAD OF
// writing a custom software rasterizer. This module owns the PGL context
// and exposes a framebuffer the runtime's render pipeline can consume.
//
// NOTE ON SHADERS: PortableGL executes C-function vertex/fragment shaders
// (its design), not GLSL source strings. The GLES20 bridge stores GLSL
// source verbatim (for inspection/trace) and real drawing goes through
// pglCreateProgram C shaders. A GLSL->C translator (or Mesa llvmpipe) is
// the future route for arbitrary APK shaders — recorded honestly in
// GLES_BACKEND_COMPARISON_010.md.
#ifndef MINIANDROID_PGL_BACKEND_H
#define MINIANDROID_PGL_BACKEND_H

#include <cstdint>
#include <string>
#include <vector>

namespace miniandroid {
namespace gles {

class PGLBackend {
public:
    // Process-wide PGL context (one software GL — the GLES20 bridge and the
    // S83 GLSurfaceView/GL10 routing drive the SAME context).
    static PGLBackend& instance();

    // Initialize (or re-initialize) the PGL context at WxH.
    bool init(int width, int height, std::string& error);

    // Bind the context as the current PGL target (no-op when inited).
    bool make_current();

    // Finish the frame: PGL swaps its back buffer internally on
    // glFlush/glFinish equivalents; call this after drawing.
    void frame_end();

    int width() const { return width_; }
    int height() const { return height_; }

    // Direct access to the PGL back buffer (pix_t = u32 RGBA8888).
    const uint32_t* pixels() const { return backbuf_; }

    bool ok() const { return inited_; }

private:
    int width_ = 0, height_ = 0;
    uint32_t* backbuf_ = nullptr;
    bool inited_ = false;
    // Opaque glContext storage (defined in portablegl.h; kept out of this
    // header so the runtime does not include PGL everywhere).
    void* ctx_ = nullptr;
};

// ── S198 F-NEW-607: the spec→PGL constant-translation law ────────────────
// PortableGL renumbers its GL enums (internal sequential C enums: draw
// modes 62-68, texture targets 108-114, types 244-250, caps, blend funcs,
// buffer bits 1<<10..12 — see src/gles/pgl_const_map.inc, GENERATED by
// scripts/s198_gen_pgl_map.py). Android/libGDX apps pass GLES 2.0 SPEC
// values (javac inlines interface constants — androguard census on
// tictactoe: ZERO GL_* sgets, all values const/16-inline). Every enum
// parameter crossing into a PGL call must be translated; unknown values
// pass through identity (PGL then records INVALID_ENUM honestly).
uint32_t pgl_from_spec(uint32_t spec_val);   // general enum slots
uint32_t pgl_mode_from_spec(uint32_t mode);  // glDrawArrays/Elements mode
uint32_t pgl_mask_from_spec(uint32_t mask);  // glClear bitfield
uint32_t pgl_to_spec(uint32_t pgl_val);      // reverse: returns/errors

// ── S198 F-NEW-609: the libGDX SpriteBatch default-shader law ───────────
// PGL executes C-function shaders; libGDX ships GLSL. The SpriteBatch
// default shader (a_position/a_color/a_texCoord0 + u_projView/u_texture)
// is the single most-deployed libGDX shader — its EXACT functional C
// equivalent lives here (impl TU). glUseProgram of an engine-minted GLSL
// program maps onto this PGL program (see gles20_bridge.cpp).
uint32_t pgl_spritebatch_program();                 // legacy first-slot face
uint32_t pgl_spritebatch_program_for(uint32_t engine_id);  // F-NEW-609b
void pgl_sb_set_proj_view(const float* m16, bool transpose);   // legacy
void pgl_sb_set_proj_view_for(uint32_t engine_id, const float* m16,
                              bool transpose);      // F-NEW-609b
int pgl_sb_uniform_location(const char* name);      // u_projView→0, u_texture→1
int pgl_sb_attrib_location(const char* name);       // position→0 color→1 tex0→2
void pgl_debug_attrib_dump(const char* tag);        // S198 corruption probe

}  // namespace gles
}  // namespace miniandroid

#endif  // MINIANDROID_PGL_BACKEND_H
