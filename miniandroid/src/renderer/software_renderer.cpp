BitmapFont::BitmapFont() {
    initialize_ascii_glyphs();
}

void BitmapFont::initialize_ascii_glyphs() {
    // EXP-092: Initialize glyphs_ from the auto-generated bitmap_font_table.
    // Table index i corresponds to ASCII char (i + 32).
    for (int i = 0; i < 95; i++) {
        const auto& entry = miniandroid::renderer::bitmap_font_table[i];
        glyphs_[i] = {entry.character, entry.width, entry.height, entry.advance, entry.bitmap};
    }
    fill_remaining_glyphs();
}

void BitmapFont::fill_remaining_glyphs() {
    // EXP-092: With the auto-generated table, every slot is already populated.
    // This function is kept for API compatibility with the previous design,
    // but it is now effectively a no-op — every glyph already has its
    // character/bitmap/advance set correctly.
    //
    // Safety check: if any glyph is still '\0' (shouldn't happen, but
    // defends against future regressions), fill it with the space bitmap
    // so we never dereference a null `bitmap` pointer.
    static const uint8_t fallback_bitmap[16] = {
        0x00, 0x00, 0x00, 0x00, 0x18, 0x18, 0x18, 0x18,
        0x18, 0x18, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
    };
    for (int i = 0; i < 95; i++) {
        if (glyphs_[i].character == '\0') {
            char c = static_cast<char>(i + 32);
            glyphs_[i] = {c, 5, 16, 6, fallback_bitmap};
        }
    }
}

const BitmapFont::Glyph* BitmapFont::get_glyph(char c) const {
    if (c >= 32 && c <= 126) {
        return &glyphs_[c - 32];
    }
    return &glyphs_[0];  // Return space for unknown chars
}

BitmapFont::TextMetrics BitmapFont::measure_text(const std::string& text) const {
    TextMetrics metrics{0, 16, 12, 4};
    
    for (char c : text) {
        const Glyph* glyph = get_glyph(c);
        metrics.width += glyph->advance;
    }
    
    return metrics;
}

json BitmapFont::to_info_json() const {
    return {
        {"font_name", "MiniAndroid_Bitmap_8x16"},
        {"glyph_count", 95},
        {"line_height", get_line_height()},
        {"baseline_offset", get_baseline_offset()},
        {"supported_range", "ASCII 32-126"}
    };
}

