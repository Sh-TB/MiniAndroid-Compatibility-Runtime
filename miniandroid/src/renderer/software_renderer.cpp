SoftwareCanvas::SoftwareCanvas(FrameBuffer* framebuffer)
    : framebuffer_(framebuffer), command_sequence_(0) {}

void SoftwareCanvas::draw_color(RGBA color) {
    framebuffer_->clear(color);
    
    CanvasCommand cmd;
    cmd.type = "drawColor";
    cmd.sequence = ++command_sequence_;
    cmd.params["color"] = color.to_json();
    commands_.push_back(cmd);
}

void SoftwareCanvas::draw_rect(float left, float top, float right, float bottom, RGBA color) {
    int x1 = static_cast<int>(std::round(left));
    int y1 = static_cast<int>(std::round(top));
    int x2 = static_cast<int>(std::round(right));
    int y2 = static_cast<int>(std::round(bottom));
    
    for (int y = y1; y < y2 && y < framebuffer_->get_height(); y++) {
        for (int x = x1; x < x2 && x < framebuffer_->get_width(); x++) {
            if (x >= 0 && y >= 0) {
                framebuffer_->set_pixel(x, y, color);
            }
        }
    }
    
    CanvasCommand cmd;
    cmd.type = "drawRect";
    cmd.sequence = ++command_sequence_;
    cmd.params["rect"] = {{"left", x1}, {"top", y1}, {"right", x2}, {"bottom", y2}};
    cmd.params["color"] = color.to_json();
    commands_.push_back(cmd);
}

void SoftwareCanvas::draw_text(const std::string& text, float x, float y, RGBA color,
                               const BitmapFont* font) {
    const BitmapFont* use_font = font ? font : &default_font_;
    
    auto metrics = use_font->measure_text(text);
    int start_x = static_cast<int>(std::round(x));
    int start_y = static_cast<int>(std::round(y)) - use_font->get_baseline_offset();
    
    // Render each character
    int current_x = start_x;
    for (char c : text) {
        const BitmapFont::Glyph* glyph = use_font->get_glyph(c);
        
        // Render glyph bitmap
        for (int row = 0; row < glyph->height; row++) {
            uint8_t bitmap_row = glyph->bitmap[row];
            for (int col = 0; col < 8; col++) {
                if (bitmap_row & (0x80 >> col)) {
                    framebuffer_->set_pixel(current_x + col, start_y + row, color);
                }
            }
        }
        
        current_x += glyph->advance;
    }
    
    CanvasCommand cmd;
    cmd.type = "drawText";
    cmd.sequence = ++command_sequence_;
    cmd.params["text"] = text;
    cmd.params["position"] = {{"x", start_x}, {"y", start_y}};
    cmd.params["color"] = color.to_json();
    cmd.params["measured_width"] = metrics.width;
    cmd.params["measured_height"] = metrics.height;
    commands_.push_back(cmd);
}

json SoftwareCanvas::to_trace_json() const {
    json trace;
    trace["total_commands"] = command_sequence_;
    trace["commands"] = json::array();
    for (const auto& cmd : commands_) {
        trace["commands"].push_back(cmd.to_json());
    }
    return trace;
}

// ============================================================================
// EXP-088 Phase A4: SoftwareCanvas::draw_image
//
// Draws an RGBA pixel buffer (decoded from a PNG via PNGDecoder) into the
// framebuffer at (dst_x, dst_y). Optional scaling to dst_w x dst_h.
//
// Uses nearest-neighbour sampling for scaling — no fancy interpolation,
// because the source PNGs we care about (simplestopwatch icons) are tiny
// and need to render at their natural size anyway.
//
// Pixels with alpha < 255 are alpha-blended onto the existing framebuffer
// pixel using the standard "over" compositing operator. This is essential
// because:
//   - simplestopwatch's lock.png is grayscale+alpha with partial transparency
//   - if we just stomped (R,G,B,0) over the framebuffer we'd lose the icon
// ============================================================================

void SoftwareCanvas::draw_image(const uint8_t* src_rgba, int src_w, int src_h,
                                int dst_x, int dst_y,
                                int dst_w, int dst_h) {
    if (!src_rgba || src_w <= 0 || src_h <= 0) return;
    if (dst_w <= 0)  dst_w = src_w;
    if (dst_h <= 0)  dst_h = src_h;

    int fb_w = framebuffer_->get_width();
    int fb_h = framebuffer_->get_height();

    for (int dy = 0; dy < dst_h; dy++) {
        int sy = (dy * src_h) / dst_h;  // nearest-neighbour
        if (sy < 0 || sy >= src_h) continue;
        for (int dx = 0; dx < dst_w; dx++) {
            int sx = (dx * src_w) / dst_w;
            if (sx < 0 || sx >= src_w) continue;

            const uint8_t* p = src_rgba + (sy * src_w + sx) * 4;
            RGBA src(p[0], p[1], p[2], p[3]);

            int x = dst_x + dx;
            int y = dst_y + dy;
            if (x < 0 || x >= fb_w || y < 0 || y >= fb_h) continue;

            // Alpha-blend with existing pixel
            RGBA dst = framebuffer_->get_pixel(x, y);
            RGBA out = blend(src, dst);
            framebuffer_->set_pixel(x, y, out);
        }
    }

    CanvasCommand cmd;
    cmd.type = "drawImage";
    cmd.sequence = ++command_sequence_;
    cmd.params["src_size"] = {{"w", src_w}, {"h", src_h}};
    cmd.params["dst_pos"]   = {{"x", dst_x}, {"y", dst_y}};
    cmd.params["dst_size"]  = {{"w", dst_w}, {"h", dst_h}};
    commands_.push_back(cmd);
}

// ============================================================================
// PNG Decoder — CAMPAIGN 010 R1: libpng-backed (replaces the EXP-088 A4
// hand-written decoder after a differential benchmark over 7,036 real APK
// PNGs showed the custom decoder failing 206 files (bit_depth 1/2/4) and
// mis-decoding 3 tRNS files, while libpng decoded 100% byte-identically to
// stb_image v2.30 and 1.65x faster than the custom code.
//
// libpng is the reference PNG implementation (libpng.org) and is the same
// decoder Android's own stack uses (libjpeg-turbo + libpng inside Skia).
// Coverage now includes everything the old code rejected:
//   - bit depths 1/2/4/8/16 (16 stripped to 8 per Android Bitmap ARGB_8888)
//   - color types 0/2/3/4/6 (palette via png_set_palette_to_rgb)
//   - tRNS transparency (png_set_expand)  [the 3-file custom-decoder bug]
//   - Adam7 interlacing (png_set_interlace_handling)
// Output contract unchanged: RGBA8 buffer, .color_type_name mirrors the
// source color type, .ok=false with descriptive error on failure.
// ============================================================================

namespace {

// libpng memory reader (whole-file buffer context)
struct PngMemCtx { const uint8_t* data; size_t size; size_t off; };

void png_mem_read(png_structp png, png_bytep out, png_size_t n) {
    PngMemCtx* c = static_cast<PngMemCtx*>(png_get_io_ptr(png));
    if (c->off + n > c->size) {
        png_error(png, "read past end of PNG buffer");
        return;
    }
    std::memcpy(out, c->data + c->off, n);
    c->off += n;
}

const char* png_color_type_name(png_byte ct) {
    switch (ct) {
        case 0: return "gray";
        case 2: return "rgb";
        case 3: return "palette→rgba";
        case 4: return "ga";
        case 6: return "rgba";
        default: return "unknown";
    }
}

}  // namespace

DecodedImage PNGDecoder::decode(const std::vector<uint8_t>& png_bytes) {
    DecodedImage result;
    if (png_bytes.size() < 8) {
        result.error = "PNG too small";
        return result;
    }
    static const uint8_t SIG[8] = {137, 80, 78, 71, 13, 10, 26, 10};
    if (std::memcmp(png_bytes.data(), SIG, 8) != 0) {
        result.error = "bad PNG signature";
        return result;
    }

    png_structp png = png_create_read_struct(PNG_LIBPNG_VER_STRING,
                                             nullptr, nullptr, nullptr);
    if (!png) {
        result.error = "png_create_read_struct failed";
        return result;
    }
    png_infop info = png_create_info_struct(png);
    if (!info) {
        png_destroy_read_struct(&png, nullptr, nullptr);
        result.error = "png_create_info_struct failed";
        return result;
    }

    PngMemCtx ctx{png_bytes.data(), png_bytes.size(), 0};
    if (setjmp(png_jmpbuf(png))) {
        png_destroy_read_struct(&png, &info, nullptr);
        result.error = "libpng: invalid or corrupted PNG stream";
        return result;
    }

    png_set_read_fn(png, &ctx, png_mem_read);
    png_read_info(png, info);

    png_byte orig_ct = png_get_color_type(png, info);
    result.color_type_name = png_color_type_name(orig_ct);

    // Android Bitmap contract: everything expands to ARGB_8888.
    png_set_palette_to_rgb(png);
    if (png_get_bit_depth(png, info) < 8) png_set_packing(png);
    if (png_get_bit_depth(png, info) == 16) png_set_strip_16(png);
    if (orig_ct == PNG_COLOR_TYPE_GRAY || orig_ct == PNG_COLOR_TYPE_GRAY_ALPHA)
        png_set_gray_to_rgb(png);
    // tRNS → full alpha channel. NOTE: png_set_expand alone does NOT expand
    // tRNS for 8-bit RGB/gray (caught by the a4 fixture test) —
    // png_set_tRNS_to_alpha covers palette/gray/RGB tRNS per PNG spec §11.3.2.
    png_set_tRNS_to_alpha(png);
    png_set_filler(png, 0xFF, PNG_FILLER_AFTER);
    png_set_interlace_handling(png);
    png_read_update_info(png, info);

    result.width  = static_cast<int>(png_get_image_width(png, info));
    result.height = static_cast<int>(png_get_image_height(png, info));
    size_t rowbytes = png_get_rowbytes(png, info);
    result.rgba.resize(rowbytes * result.height);
    std::vector<png_bytep> rows(result.height);
    for (int y = 0; y < result.height; y++)
        rows[y] = result.rgba.data() + static_cast<size_t>(y) * rowbytes;

    png_read_image(png, rows.data());
    png_read_end(png, nullptr);
    png_destroy_read_struct(&png, &info, nullptr);

    result.ok = true;
    return result;
}

DecodedImage PNGDecoder::decode_file(const std::string& path) {
    std::ifstream f(path, std::ios::binary | std::ios::ate);
    if (!f.is_open()) {
        DecodedImage r;
        r.error = "cannot open file: " + path;
        return r;
    }
    auto sz = f.tellg();
    f.seekg(0, std::ios::beg);
    std::vector<uint8_t> buf(sz);
    f.read(reinterpret_cast<char*>(buf.data()), sz);
    return decode(buf);
}

