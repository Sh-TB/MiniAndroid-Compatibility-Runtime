class Config:
    """Configuration pointing to real runtime."""
    
    BASE_DIR = Path(__file__).parent.parent
    RUNTIME_BINARY = BASE_DIR / "build" / "miniandroid"
    DOWNLOAD_DIR = BASE_DIR / "download" / "apks"
    RUN_DIR = BASE_DIR / "run" / "exp026"
    RESULTS_DIR = RUN_DIR / "results"
    TRACES_DIR = RUN_DIR / "traces"
    REGISTRY_PATH = BASE_DIR / "database" / "exp025_apk_registry.json"
    
    @classmethod
    def ensure_dirs(cls):
        cls.RUN_DIR.mkdir(parents=True, exist_ok=True)
        cls.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
        cls.TRACES_DIR.mkdir(parents=True, exist_ok=True)
    
    @classmethod
    def verify_runtime(cls) -> Tuple[bool, str]:
        """Verify runtime binary exists and is executable."""
        if not cls.RUNTIME_BINARY.exists():
            return False, f"Runtime binary not found: {cls.RUNTIME_BINARY}"
        if not os.access(cls.RUNTIME_BINARY, os.X_OK):
            return False, f"Runtime binary not executable: {cls.RUNTIME_BINARY}"
        return True, f"Runtime verified: {cls.RUNTIME_BINARY}"


# ============================================================================
# Strict Execution Status (No Simulation)
# ============================================================================

class RealExecutionStatus(Enum):
    """
    STRICT status from REAL execution only.
    
    These are the ONLY valid statuses - all from actual runtime behavior.
    """
    EXECUTED_PASS = "EXECUTED_PASS"         # Runtime returned SUCCESS
    EXECUTED_PARTIAL = "EXECUTED_PARTIAL"   # Runtime completed with warnings
    EXECUTED_FAIL = "EXECUTED_FAIL"         # Runtime returned FAILURE or crashed
    PARSE_ERROR = "PARSE_ERROR"             # APK could not be parsed by runtime
    RUNTIME_ERROR = "RUNTIME_ERROR"         # Runtime itself failed (segfault, etc.)
    NOT_EXECUTED = "NOT_EXECUTED"           # Could not attempt execution


# ============================================================================
# Data Structures for Real Execution Results
# ============================================================================

@dataclass
class RealExecutionResult:
    """Result from ACTUAL runtime execution (not simulation)."""
    
    # Identification
    apk_name: str
    package_name: str
    execution_id: str
    timestamp: str
    
    # Status (from real execution)
    status: RealExecutionStatus
    real_execution: bool  # Always True for this runner
    
    # Runtime info
    runtime_version: str
    runtime_path: str
    
    # Timing
    start_time: str
    end_time: str
    duration_ms: int
    
    # APK Analysis (from runtime)
    apk_sha256: str
    dex_loaded: bool
    entry_activity: str
    dex_files: List[str]
    
    # Execution Metrics (from runtime output)
    instructions_executed: int
    api_calls: List[Dict[str, Any]]
    frames_rendered: int
    
    # Missing/Failed items
    missing_opcodes: List[str]
    missing_apis: List[str]
    
    # Errors from runtime
    runtime_errors: List[str]
    runtime_warnings: List[str]
    crash_log: Optional[str]
    
    # Evidence files (generated by runtime)
    trace_file: str
    api_trace_file: str
    screenshot_file: str
    report_file: str
    output_directory: str
    
    # Notes
    notes: str
    
    def to_dict(self) -> dict:
        result = asdict(self)
        result['status'] = self.status.value
        return result


