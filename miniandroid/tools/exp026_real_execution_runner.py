class EXP026CampaignRunner:
    """
    Runs EXP-026 campaign with REAL execution (no simulation).
    """
    
    def __init__(self):
        self.engine = RealExecutionEngine()
        self.results: List[Dict] = []
        self.registry: List[Dict] = []
        
        # Statistics (from REAL executions only)
        self.stats = {
            'total_apks': 0,
            'executed_pass': 0,
            'executed_partial': 0,
            'executed_fail': 0,
            'parse_error': 0,
            'runtime_error': 0,
            'not_executed': 0,
            'total_execution_time_ms': 0,
            'real_api_frequency': {},
            'real_opcode_usage': {},
            'runtime_failures': []
        }
    
    def load_registry(self):
        """Load APK registry from EXP-025 or scan download directory."""
        registry_path = Config.REGISTRY_PATH
        download_dir = Config.DOWNLOAD_DIR
        
        # Try loading from registry first
        if registry_path.exists():
            with open(registry_path, 'r') as f:
                raw_data = json.load(f)
            
            # Registry can be dict (package->info) or list
            if isinstance(raw_data, dict):
                self.registry = list(raw_data.values())
            elif isinstance(raw_data, list):
                self.registry = raw_data
            else:
                self.registry = []
            
            # Filter to only APKs that were actually downloaded and exist
            verified = [
                apk for apk in self.registry 
                if apk.get('status') in ['verified', 'downloaded'] 
                and apk.get('local_path')
                and Path(apk['local_path']).exists()
            ]
            
            if verified:
                self.registry = verified
                print(f"\n[INFO] Loaded {len(self.registry)} verified APKs from registry")
                return
        
        # Fallback: Scan download directory for APK files
        print(f"\n[INFO] Scanning {download_dir} for APK files...")
        
        if download_dir.exists():
            self.registry = []
            for apk_file in sorted(download_dir.glob('*.apk')):
                apk_info = {
                    'name': apk_file.stem,
                    'package': f'generated.{apk_file.stem.lower()}',
                    'version': '1.0',
                    'source': 'local',
                    'status': 'verified',
                    'local_path': str(apk_file),
                    'category': 'Generated',
                    'tier': 1
                }
                self.registry.append(apk_info)
            
            print(f"[INFO] Found {len(self.registry)} APK files in download directory")
        else:
            print(f"\n[WARN] No APKs found!")
            self.registry = []
    
    def run_campaign(self):
        """Execute campaign with REAL runtime on all APKs."""
        
        print("\n" + "=" * 70)
        print("  EXP-026 REAL EXECUTION CAMPAIGN")
        print("  NO SIMULATION — ONLY REAL RUNTIME EXECUTION")
        print("=" * 70)
        print(f"  Time: {datetime.now().isoformat()}")
        print(f"  Runtime: {self.engine.runtime_version}")
        print("=" * 70)
        
        # Load APKs
        self.load_registry()
        
        if not self.registry:
            print("[ERROR] No APKs in registry!")
            return
        
        self.stats['total_apks'] = len(self.registry)
        
        print(f"\n[CAMPAIGN] Executing {len(self.registry)} APKs through REAL runtime\n")
        
        # Execute each APK
        for i, apk_info in enumerate(self.registry, 1):
            apk_path = Path(apk_info.get('local_path', ''))
            
            if not apk_path.exists():
                print(f"\n[{i}/{len(self.registry)}] SKIP: {apk_info.get('name', '?')} — file not found")
                self.results.append({
                    'apk_info': apk_info,
                    'status': 'NOT_EXECUTED',
                    'error': 'APK file not found',
                    'real_execution': False
                })
                self.stats['not_executed'] += 1
                continue
            
            print(f"\n[{i}/{len(self.registry)}] Processing: {apk_info.get('name', '?')}")
            
            # Execute through REAL runtime
            result = self.engine.execute_apk(apk_path)
            result_dict = result.to_dict()
            result_dict['apk_info'] = apk_info
            self.results.append(result_dict)
            
            # Update statistics
            status_str = result.status.value
            stat_key = status_str.lower()
            if stat_key in self.stats:
                self.stats[stat_key] += 1
            
            self.stats['total_execution_time_ms'] += result.duration_ms
            
            # Collect real API frequency
            self._update_api_frequency(result)
            
            # Small delay between executions
            time.sleep(0.5)
        
        # Generate report
        self._generate_report()
    
    def _update_api_frequency(self, result: RealExecutionResult):
        """Update API frequency from REAL execution data."""
        
        for api_call in result.api_calls:
            if isinstance(api_call, dict):
                # Extract API identifier
                class_name = api_call.get('class', '')
                method_name = api_call.get('method', '')
                
                if class_name and method_name:
                    api_key = f"{class_name}.{method_name}"
                    
                    if api_key not in self.stats['real_api_frequency']:
                        self.stats['real_api_frequency'][api_key] = {
                            'count': 0,
                            'apps': [],
                            'success_count': 0,
                            'fail_count': 0
                        }
                    
                    self.stats['real_api_frequency'][api_key]['count'] += 1
                    self.stats['real_api_frequency'][api_key]['apps'].append(
                        result.package_name or result.apk_name
                    )
                    
                    if api_call.get('success', True):
                        self.stats['real_api_frequency'][api_key]['success_count'] += 1
                    else:
                        self.stats['real_api_frequency'][api_key]['fail_count'] += 1
        
        # Record failures
        if result.status in [RealExecutionStatus.EXECUTED_FAIL, RealExecutionStatus.PARSE_ERROR]:
            failure = {
                'package': result.package_name or result.apk_name,
                'status': result.status.value,
                'errors': result.runtime_errors[:3],
                'has_crash_log': bool(result.crash_log),
                'timestamp': result.timestamp
            }
            self.stats['runtime_failures'].append(failure)
    
    def _generate_report(self):
        """Generate final campaign report."""
        
        print("\n" + "=" * 70)
        print("  REAL EXECUTION RESULTS")
        print("=" * 70)
        
        print(f"\n  Total APKs:     {self.stats['total_apks']}")
        print(f"  EXECUTED_PASS:  {self.stats['executed_pass']}")
        print(f"  EXECUTED_PARTIAL: {self.stats['executed_partial']}")
        print(f"  EXECUTED_FAIL:  {self.stats['executed_fail']}")
        print(f"  PARSE_ERROR:    {self.stats['parse_error']}")
        print(f"  RUNTIME_ERROR:  {self.stats['runtime_error']}")
        print(f"  NOT_EXECUTED:   {self.stats['not_executed']}")
        
        # Calculate TRUE compatibility score (only from real executions)
        total_executed = (
            self.stats['executed_pass'] + 
            self.stats['executed_partial'] + 
            self.stats['executed_fail']
        )
        
        if total_executed > 0:
            true_score = (
                (self.stats['executed_pass'] * 100) +
                (self.stats['executed_partial'] * 50)
            ) / total_executed
            
            print(f"\n  TRUE COMPATIBILITY SCORE (from {total_executed} REAL executions):")
            print(f"    Score: {true_score:.1f}/100")
            print(f"    Pass Rate: {(self.stats['executed_pass']/total_executed)*100:.1f}%")
            print(f"    Partial Rate: {(self.stats['executed_partial']/total_executed)*100:.1f}%")
            print(f"    Fail Rate: {(self.stats['executed_fail']/total_executed)*100:.1f}%")
        else:
            true_score = 0
            print(f"\n  COMPATIBILITY SCORE: N/A (no apps executed)")
        
        # Top APIs used
        print(f"\n  TOP APIs (from REAL execution):")
        sorted_apis = sorted(
            self.stats['real_api_frequency'].items(),
            key=lambda x: x[1]['count'],
            reverse=True
        )[:10]
        
        for i, (api, data) in enumerate(sorted_apis, 1):
            print(f"    {i}. {api}: {data['count']} calls ({len(data['apps'])} apps)")
        
        print("=" * 70)
        
        # Save results
        self._save_results(true_score, total_executed)
    
    def _save_results(self, score: float, executed_count: int):
        """Save all results to disk."""
        
        # Full results
        results_path = Config.RESULTS_DIR / "exp026_real_execution_results.json"
        with open(results_path, 'w') as f:
            json.dump(self.results, f, indent=2, default=str)
        
        # Summary with TRUE score
        summary = {
            'experiment': 'EXP-026',
            'phase': 'REAL_EXECUTION_COMPLETE',
            'timestamp': datetime.now().isoformat(),
            'mode': 'REAL_EXECUTION',  # NOT SIMULATION!
            'runtime_version': self.engine.runtime_version,
            'score': {
                'value': round(score, 2),
                'max_possible': 100,
                'based_on': 'REAL_EXECUTION_ONLY',  # Critical distinction
                'total_executed': executed_count,
                'formula': '(PASS*100 + PARTIAL*50) / executed',
                'honesty_note': 'This score is from REAL runtime execution, not simulation'
            },
            'statistics': self.stats,
            'golden_debug_protocol': {
                'simulation_used': False,
                'all_results_from_real_runtime': True,
                'evidence_files_generated_by_runtime': True,
                'no_projected_scores': True
            }
        }
        
        summary_path = Config.RUN_DIR / "exp026_true_compatibility_score.json"
        with open(summary_path, 'w') as f:
            json.dump(summary, f, indent=2, default=str)
        
        # Real API usage database
        api_db_path = Config.BASE_DIR / "database" / "exp026_real_api_usage.json"
        with open(api_db_path, 'w') as f:
            json.dump(self.stats['real_api_frequency'], f, indent=2)
        
        # Failure database
        failure_db_path = Config.BASE_DIR / "database" / "exp026_runtime_failures.json"
        with open(failure_db_path, 'w') as f:
            json.dump(self.stats['runtime_failures'], f, indent=2)
        
        print(f"\n[SAVED] Results: {results_path}")
        print(f"[SAVED] TRUE Score: {summary_path}")
        print(f"[SAVED] API Usage: {api_db_path}")
        print(f"[SAVED] Failures: {failure_db_path}")


