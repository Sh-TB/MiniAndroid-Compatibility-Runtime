# Real Execution Engine — Uses Actual Binary
# ============================================================================

class RealExecutionEngine:
    """
    Executes APKs using the REAL MiniAndroid runtime binary.
    
    NO SIMULATION. Only actual subprocess calls to build/miniandroid.
    """
    
    def __init__(self):
        Config.ensure_dirs()
        
        # Verify runtime exists
        self.runtime_ok, self.runtime_msg = Config.verify_runtime()
        if not self.runtime_ok:
            print(f"[FATAL] {self.runtime_msg}")
            raise RuntimeError(f"Runtime not available: {self.runtime_msg}")
        
        self.runtime_path = str(Config.RUNTIME_BINARY)
        self.runtime_version = self._get_runtime_version()
        
        print(f"[INIT] Real Execution Engine ready")
        print(f"       Runtime: {self.runtime_path}")
        print(f"       Version: {self.runtime_version}")
    
    def _get_runtime_version(self) -> str:
        """Get runtime version string."""
        try:
            result = subprocess.run(
                [self.runtime_path, 'version'],
                capture_output=True,
                text=True,
                timeout=10
            )
            return result.stdout.strip()[:100]
        except Exception as e:
            return f"Unknown (error: {e})"
    
    def _calculate_sha256(self, path: Path) -> str:
        """Calculate SHA256 of a file."""
        h = hashlib.sha256()
        with open(path, 'rb') as f:
            for chunk in iter(lambda: f.read(8192), b''):
                h.update(chunk)
        return h.hexdigest()
    
    def execute_apk(self, apk_path: Path, output_dir: Optional[Path] = None) -> RealExecutionResult:
        """
        Execute an APK through the REAL MiniAndroid runtime.
        
        This is NOT simulation. It calls the actual compiled binary.
        """
        
        start_time = datetime.now()
        execution_id = f"real_{start_time.strftime('%Y%m%d_%H%M%S')}_{apk_path.stem}"
        
        if output_dir is None:
            output_dir = Config.TRACES_DIR / execution_id
        
        output_dir.mkdir(parents=True, exist_ok=True)
        
        print(f"\n{'='*60}")
        print(f"[REAL EXECUTE] {apk_path.name}")
        print(f"  ID: {execution_id}")
        print(f"  Mode: REAL (no simulation)")
        print(f"{'='*60}")
        
        # Initialize result structure
        result = RealExecutionResult(
            apk_name=apk_path.name,
            package_name="unknown",
            execution_id=execution_id,
            timestamp=start_time.isoformat(),
            status=RealExecutionStatus.NOT_EXECUTED,
            real_execution=True,  # ALWAYS TRUE for this runner
            runtime_version=self.runtime_version,
            runtime_path=self.runtime_path,
            start_time=start_time.isoformat(),
            end_time="",
            duration_ms=0,
            apk_sha256="",
            dex_loaded=False,
            entry_activity="",
            dex_files=[],
            instructions_executed=0,
            api_calls=[],
            frames_rendered=0,
            missing_opcodes=[],
            missing_apis=[],
            runtime_errors=[],
            runtime_warnings=[],
            crash_log=None,
            trace_file="",
            api_trace_file="",
            screenshot_file="",
            report_file="",
            output_directory=str(output_dir),
            notes=""
        )
        
        try:
            # Verify APK exists
            if not apk_path.exists():
                raise FileNotFoundError(f"APK not found: {apk_path}")
            
            # Calculate SHA256
            result.apk_sha256 = self._calculate_sha256(apk_path)
            print(f"  [SHA256] {result.apk_sha256[:32]}...")
            
            # Execute using REAL runtime
            print(f"  [RUN] Calling runtime...")
            exec_start = time.time()
            
            proc = subprocess.run(
                [
                    self.runtime_path,
                    'run',
                    '-o', str(output_dir),
                    str(apk_path)
                ],
                capture_output=True,
                text=True,
                timeout=120  # 2 minute timeout per APK
            )
            
            exec_duration_ms = int((time.time() - exec_start) * 1000)
            result.duration_ms = exec_duration_ms
            
            end_time = datetime.now()
            result.end_time = end_time.isoformat()
            
            # Capture stdout/stderr
            stdout_text = proc.stdout
            stderr_text = proc.stderr
            
            print(f"\n  [STDOUT]")
            for line in stdout_text.split('\n')[:20]:  # First 20 lines
                if line.strip():
                    print(f"    {line}")
            
            if stderr_text.strip():
                print(f"  [STDERR]")
                for line in stderr_text.split('\n')[:10]:
                    if line.strip():
                        print(f"    {line}")
            
            # Parse runtime output for metrics
            self._parse_runtime_output(result, stdout_text, proc.returncode)
            
            # Collect evidence files
            self._collect_evidence(result, output_dir)
            
            # Determine final status based on REAL execution
            result.status = self._classify_real_result(proc.returncode, result)
            
            print(f"\n  [STATUS] {result.status.value} ({exec_duration_ms}ms)")
            
        except subprocess.TimeoutExpired:
            result.status = RealExecutionStatus.EXECUTED_FAIL
            result.runtime_errors.append("Execution timed out (120s limit)")
            result.end_time = datetime.now().isoformat()
            result.duration_ms = 120000
            print(f"\n  [TIMEOUT] Execution exceeded time limit")
            
        except FileNotFoundError as e:
            result.status = RealExecutionStatus.NOT_EXECUTED
            result.runtime_errors.append(str(e))
            print(f"\n  [ERROR] {e}")
            
        except Exception as e:
            result.status = RealExecutionStatus.RUNTIME_ERROR
            result.runtime_errors.append(f"Unexpected error: {str(e)}")
            result.end_time = datetime.now().isoformat()
            print(f"\n  [ERROR] {e}")
        
        # Save trace
        trace_path = Config.TRACES_DIR / f"{execution_id}_result.json"
        with open(trace_path, 'w') as f:
            json.dump(result.to_dict(), f, indent=2, default=str)
        result.trace_file = str(trace_path)
        
        return result
    
    def _parse_runtime_output(self, result: RealExecutionResult, stdout: str, returncode: int):
        """Parse runtime output to extract metrics."""
        
        lines = stdout.lower()
        
        # Look for success/failure indicators
        if 'success' in lines or '✓' in stdout or returncode == 0:
            pass  # Will be classified as PASS or PARTIAL based on other factors
        
        if 'error' in lines or 'fail' in stdout:
            result.runtime_errors.append("Runtime reported errors")
        
        if 'warning' in lines:
            result.runtime_warnings.append("Runtime reported warnings")
        
        # Try to extract package name from output
        if 'package' in stdout:
            import re
            pkg_match = re.search(r'package[_\s]*(name)?["\s:]+([a-z0-9_.]+)', stdout, re.IGNORECASE)
            if pkg_match:
                result.package_name = pkg_match.group(2)
        
        # Check for DEX loading indicators
        if 'dex' in lines or 'classes.dex' in lines:
            result.dex_loaded = True
            result.dex_files.append("classes.dex")
        
        # Check for activity indicators
        if 'activity' in lines:
            result.entry_activity = "detected"
    
    def _collect_evidence(self, result: RealExecutionResult, output_dir: Path):
        """Collect evidence files generated by runtime."""
        
        expected_files = {
            'api_trace': 'api_trace.json',
            'crash_log': 'crash.log', 
            'report': 'report.md',
            'screenshot': 'screenshot.ppm'
        }
        
        for key, filename in expected_files.items():
            file_path = output_dir / filename
            if file_path.exists():
                if key == 'api_trace':
                    result.api_trace_file = str(file_path)
                    # Try to parse API trace
                    try:
                        with open(file_path, 'r') as f:
                            api_data = json.load(f)
                            if isinstance(api_data, list):
                                result.api_calls = api_data
                            elif isinstance(api_data, dict):
                                result.api_calls = api_data.get('calls', [])
                    except:
                        pass
                
                elif key == 'crash_log':
                    with open(file_path, 'r') as f:
                        content = f.read().strip()
                        if content and content != 'No crash':
                            result.crash_log = content
                            result.runtime_errors.append(f"Crash: {content[:200]}")
                
                elif key == 'screenshot':
                    result.screenshot_file = str(file_path)
                    result.frames_rendered = 1  # Screenshot means frame was rendered
                
                elif key == 'report':
                    result.report_file = str(file_path)
    
    def _classify_real_result(self, returncode: int, result: RealExecutionResult) -> RealExecutionStatus:
        """Classify result based on REAL execution evidence."""
        
        # If there's a crash log, it's a FAIL
        if result.crash_log:
            return RealExecutionStatus.EXECUTED_FAIL
        
        # If there are critical errors, it's a FAIL
        critical_errors = [e for e in result.runtime_errors if 'crash' in e.lower() or 'fatal' in e.lower()]
        if critical_errors:
            return RealExecutionStatus.EXECUTED_FAIL
        
        # If we have API calls and/or screenshots, execution proceeded
        if result.api_calls or result.screenshot_file:
            if result.runtime_warnings:
                return RealExecutionStatus.EXECUTED_PARTIAL
            else:
                return RealExecutionStatus.EXECUTED_PASS
        
        # If return code is non-zero but no clear failure
        if returncode != 0:
            if result.dex_loaded:
                return RealExecutionStatus.EXECUTED_PARTIAL
            else:
                return RealExecutionStatus.PARSE_ERROR
        
        # Default to PASS if we got here with returncode 0
        if returncode == 0:
            return RealExecutionStatus.EXECUTED_PASS
        
        return RealExecutionStatus.EXECUTED_FAIL


